#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(scriptDir, "..");
const brandingDir = join(rootDir, "assets", "branding");
const masterPath = join(brandingDir, "favicon-master.svg");
const manifestPath = join(rootDir, "site.webmanifest");
const workDir = mkdtempSync(join(tmpdir(), "windwoods-favicon-"));

const browserCandidates = [
  process.env.FAVICON_BROWSER,
  "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe",
  "C:\\Program Files\\Microsoft\\Edge\\Application\\msedge.exe",
  "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe",
  "C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe",
  "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  "/usr/bin/microsoft-edge",
  "/usr/bin/google-chrome",
  "/usr/bin/chromium",
].filter(Boolean);

const browserPath = browserCandidates.find((candidate) => existsSync(candidate));

if (!browserPath) {
  throw new Error(
    "Edge/Chrome/Chromium was not found. Set FAVICON_BROWSER to its executable path.",
  );
}

mkdirSync(brandingDir, { recursive: true });

const masterSvg = readFileSync(masterPath, "utf8");
const flatSvg = masterSvg
  .replace(/<defs>[\s\S]*?<\/defs>\s*/, "")
  .replace('fill="url(#gold-gradient)"', 'fill="#d3b965"')
  .replace(
    "<?xml version=\"1.0\" encoding=\"UTF-8\"?>",
    '<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/generate-favicons.mjs. Edit assets/branding/favicon-master.svg instead. -->',
  );
const appleSvg = masterSvg
  .replace('viewBox="0 0 1024 1024"', 'viewBox="-64 -64 1152 1152"')
  .replace(
    '<rect id="background" x="0" y="0" width="1024" height="1024" fill="#050505"/>',
    '<rect id="background" x="-64" y="-64" width="1152" height="1152" fill="#050505"/>',
  );

writeFileSync(join(rootDir, "favicon.svg"), flatSvg);

function renderSvg(svg, size, outputPath, label) {
  const svgPath = join(workDir, `${label}-${size}.svg`);
  const htmlPath = join(workDir, `${label}-${size}.html`);
  const profilePath = join(workDir, `profile-${label}-${size}`);

  writeFileSync(svgPath, svg);
  writeFileSync(
    htmlPath,
    `<!doctype html><meta charset="utf-8"><style>html,body{margin:0;overflow:hidden;background:#050505}img{display:block;width:${size}px;height:${size}px}</style><img src="${pathToFileURL(svgPath).href}" alt="">`,
  );

  const result = spawnSync(
    browserPath,
    [
      "--headless=new",
      "--disable-gpu",
      "--disable-extensions",
      "--disable-background-networking",
      "--hide-scrollbars",
      "--no-first-run",
      "--force-device-scale-factor=1",
      "--run-all-compositor-stages-before-draw",
      `--user-data-dir=${profilePath}`,
      `--window-size=${size},${size}`,
      `--screenshot=${outputPath}`,
      pathToFileURL(htmlPath).href,
    ],
    { encoding: "utf8" },
  );

  if (result.status !== 0 || !existsSync(outputPath)) {
    throw new Error(
      `Failed to render ${label} at ${size}px.\n${result.stderr || result.stdout}`,
    );
  }

  const dimensions = readPngDimensions(outputPath);
  if (dimensions.width !== size || dimensions.height !== size) {
    throw new Error(
      `${outputPath} is ${dimensions.width}x${dimensions.height}; expected ${size}x${size}.`,
    );
  }
}

function readPngDimensions(filePath) {
  const png = readFileSync(filePath);
  const signature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
  if (!png.subarray(0, 8).equals(signature) || png.toString("ascii", 12, 16) !== "IHDR") {
    throw new Error(`${filePath} is not a valid PNG.`);
  }
  return {
    width: png.readUInt32BE(16),
    height: png.readUInt32BE(20),
  };
}

function buildPngIco(entries, outputPath) {
  const images = entries.map(({ size, filePath }) => ({
    size,
    data: readFileSync(filePath),
  }));
  const directory = Buffer.alloc(6 + images.length * 16);
  directory.writeUInt16LE(0, 0);
  directory.writeUInt16LE(1, 2);
  directory.writeUInt16LE(images.length, 4);

  let offset = directory.length;
  images.forEach(({ size, data }, index) => {
    const entryOffset = 6 + index * 16;
    directory.writeUInt8(size === 256 ? 0 : size, entryOffset);
    directory.writeUInt8(size === 256 ? 0 : size, entryOffset + 1);
    directory.writeUInt8(0, entryOffset + 2);
    directory.writeUInt8(0, entryOffset + 3);
    directory.writeUInt16LE(1, entryOffset + 4);
    directory.writeUInt16LE(32, entryOffset + 6);
    directory.writeUInt32LE(data.length, entryOffset + 8);
    directory.writeUInt32LE(offset, entryOffset + 12);
    offset += data.length;
  });

  writeFileSync(outputPath, Buffer.concat([directory, ...images.map(({ data }) => data)]));
}

const icoEntries = [16, 32, 48].map((size) => ({
  size,
  filePath: join(workDir, `favicon-${size}.png`),
}));

try {
  renderSvg(masterSvg, 1024, join(brandingDir, "favicon-master-1024.png"), "master");
  renderSvg(masterSvg, 96, join(rootDir, "favicon-96x96.png"), "favicon");
  renderSvg(appleSvg, 180, join(rootDir, "apple-touch-icon.png"), "apple-touch-icon");
  renderSvg(
    masterSvg,
    192,
    join(rootDir, "web-app-manifest-192x192.png"),
    "web-app-manifest",
  );
  renderSvg(
    masterSvg,
    512,
    join(rootDir, "web-app-manifest-512x512.png"),
    "web-app-manifest",
  );
  icoEntries.forEach(({ size, filePath }) =>
    renderSvg(flatSvg, size, filePath, "favicon-flat"),
  );
  buildPngIco(icoEntries, join(rootDir, "favicon.ico"));

  writeFileSync(
    manifestPath,
    `${JSON.stringify(
      {
        name: "WindWoods",
        short_name: "WindWoods",
        icons: [
          {
            src: "/web-app-manifest-192x192.png",
            sizes: "192x192",
            type: "image/png",
          },
          {
            src: "/web-app-manifest-512x512.png",
            sizes: "512x512",
            type: "image/png",
          },
        ],
        theme_color: "#050505",
        background_color: "#050505",
        display: "standalone",
        start_url: "/",
        scope: "/",
      },
      null,
      2,
    )}\n`,
  );

  console.log(`Generated favicon set with ${browserPath}:`);
  [
    "assets/branding/favicon-master-1024.png",
    "favicon.ico (16, 32, 48)",
    "favicon.svg",
    "favicon-96x96.png",
    "apple-touch-icon.png",
    "web-app-manifest-192x192.png",
    "web-app-manifest-512x512.png",
    "site.webmanifest",
  ].forEach((file) => console.log(`- ${file}`));
} finally {
  try {
    rmSync(workDir, { recursive: true, force: true });
  } catch {
    console.warn(`Temporary render directory could not be removed: ${workDir}`);
  }
}
